//! Registro de todas las rutas HTTP del servicio.
//!
//! El orden replica los controladores Nest: las rutas estáticas se registran
//! antes que las paramétricas (`proyecciones/sensibilidad` antes que
//! `proyecciones/:id`) para no taparlas (R-DO-9).

use crate::http::{comercio, finanzas, interno};
use crate::state::AppState;
use axum::routing::{delete, get, patch, post, put};
use axum::Router;

pub fn registrar(router: Router<AppState>) -> Router<AppState> {
    router
        // ── comercio ────────────────────────────────────────────────────────
        .route(
            "/api/v2/comercio/bancos-cuentas",
            get(comercio::bancos_listar).post(comercio::bancos_crear),
        )
        .route(
            "/api/v2/comercio/bancos-cuentas/{id}",
            patch(comercio::bancos_actualizar).delete(comercio::bancos_eliminar),
        )
        .route(
            "/api/v2/comercio/creditos",
            get(comercio::creditos_listar).post(comercio::creditos_crear),
        )
        .route(
            "/api/v2/comercio/creditos/{id}",
            delete(comercio::creditos_eliminar),
        )
        .route(
            "/api/v2/comercio/creditos/{id}/pagar",
            post(comercio::creditos_pagar),
        )
        .route(
            "/api/v2/comercio/creditos/{id}/abonar",
            post(comercio::creditos_abonar),
        )
        .route(
            "/api/v2/comercio/credito-cuentas",
            get(comercio::cuentas_credito_listar),
        )
        .route(
            "/api/v2/comercio/credito-cuentas/{parteId}",
            put(comercio::cuentas_credito_guardar),
        )
        .route(
            "/api/v2/comercio/gastos",
            get(comercio::gastos_listar).post(comercio::gastos_crear),
        )
        .route(
            "/api/v2/comercio/gastos/{id}",
            patch(comercio::gastos_actualizar).delete(comercio::gastos_eliminar),
        )
        .route(
            "/api/v2/comercio/gastos/{id}/pagar",
            post(comercio::gasto_pagar),
        )
        .route(
            "/api/v2/comercio/gastos/{id}/cancelar",
            post(comercio::gasto_cancelar),
        )
        .route(
            "/api/v2/comercio/cuentas-por-pagar",
            get(comercio::cuentas_por_pagar_listar).post(comercio::cuentas_por_pagar_crear),
        )
        .route(
            "/api/v2/comercio/cuentas-por-pagar/{id}",
            delete(comercio::cuentas_por_pagar_eliminar),
        )
        .route(
            "/api/v2/comercio/cuentas-por-pagar/{id}/pagar",
            post(comercio::cuentas_por_pagar_pagar),
        )
        .route(
            "/api/v2/comercio/proveedores",
            get(comercio::proveedores_listar).post(comercio::proveedores_crear),
        )
        .route(
            "/api/v2/comercio/proveedores/{id}",
            delete(comercio::proveedores_eliminar),
        )
        .route(
            "/api/v2/comercio/compras",
            get(comercio::compras_listar).post(comercio::compras_crear),
        )
        .route(
            "/api/v2/comercio/compras/directas",
            post(comercio::compras_directas),
        )
        .route(
            "/api/v2/comercio/compras/producto-nuevo",
            post(comercio::compras_producto_nuevo),
        )
        .route(
            "/api/v2/comercio/compras/{id}",
            delete(comercio::compras_eliminar),
        )
        .route(
            "/api/v2/comercio/compras/{id}/anular",
            post(comercio::compras_anular),
        )
        .route(
            "/api/v2/comercio/ordenes-compra",
            get(comercio::ordenes_compra_listar).post(comercio::ordenes_compra_crear),
        )
        .route(
            "/api/v2/comercio/ordenes-compra/{id}/convertir",
            post(comercio::ordenes_compra_convertir),
        )
        .route(
            "/api/v2/comercio/ordenes-compra/{id}/anular",
            post(comercio::ordenes_compra_anular),
        )
        .route(
            "/api/v2/comercio/configuracion-documentos",
            get(comercio::configuracion_documentos_obtener)
                .put(comercio::configuracion_documentos_guardar),
        )
        .route(
            "/api/v2/comercio/caja/metodos-pago",
            get(comercio::metodos_pago_listar).post(comercio::metodos_pago_crear),
        )
        .route(
            "/api/v2/comercio/caja/metodos-pago/{id}",
            patch(comercio::metodos_pago_actualizar).delete(comercio::metodos_pago_eliminar),
        )
        .route(
            "/api/v2/comercio/caja/movimientos",
            get(comercio::movimientos_caja_listar).post(comercio::movimientos_caja_crear),
        )
        .route(
            "/api/v2/comercio/caja/movimientos/{id}",
            delete(comercio::movimientos_caja_eliminar),
        )
        .route(
            "/api/v2/comercio/caja/movimientos/{id}/anular",
            post(comercio::movimiento_caja_anular),
        )
        .route(
            "/api/v2/comercio/caja/cierres",
            get(comercio::cierres_listar).post(comercio::cierres_crear),
        )
        .route(
            "/api/v2/comercio/caja/cierres/preview",
            get(comercio::cierres_preview),
        )
        .route(
            "/api/v2/comercio/caja/chica/fondo",
            get(comercio::caja_chica_fondo_obtener).put(comercio::caja_chica_fondo_guardar),
        )
        .route(
            "/api/v2/comercio/caja/chica/movimientos",
            get(comercio::caja_chica_movimientos_listar)
                .post(comercio::caja_chica_movimientos_crear),
        )
        .route(
            "/api/v2/comercio/caja/transferencias",
            get(comercio::transferencias_listar).post(comercio::transferencias_crear),
        )
        .route(
            "/api/v2/comercio/caja/transferencias/{id}/anular",
            post(comercio::transferencias_anular),
        )
        .route(
            "/api/v2/comercio/clientes",
            get(comercio::clientes_listar).post(comercio::clientes_crear),
        )
        .route(
            "/api/v2/comercio/clientes/importar",
            post(comercio::clientes_importar),
        )
        .route(
            "/api/v2/comercio/clientes/{id}",
            patch(comercio::clientes_actualizar).delete(comercio::clientes_eliminar),
        )
        .route(
            "/api/v2/comercio/codigos-barras",
            get(comercio::codigos_barras_listar).post(comercio::codigos_barras_crear),
        )
        .route(
            "/api/v2/comercio/codigos-barras/{id}",
            delete(comercio::codigos_barras_eliminar),
        )
        // ── finanzas: contabilidad ──────────────────────────────────────────
        .route(
            "/api/v2/finanzas/cuentas",
            get(finanzas::cuentas_listar).post(finanzas::cuentas_crear),
        )
        .route(
            "/api/v2/finanzas/cuentas/{codigo}/estado",
            post(finanzas::cuenta_estado),
        )
        .route(
            "/api/v2/finanzas/asientos",
            get(finanzas::asientos_listar).post(finanzas::asiento_crear),
        )
        .route(
            "/api/v2/finanzas/asientos/{id}/anular",
            post(finanzas::asiento_anular),
        )
        .route(
            "/api/v2/finanzas/libro-mayor/{cuenta}",
            get(finanzas::libro_mayor),
        )
        .route("/api/v2/finanzas/libro-ventas", get(finanzas::libro_ventas))
        .route(
            "/api/v2/finanzas/libro-compras",
            get(finanzas::libro_compras),
        )
        // ── finanzas: tributación ───────────────────────────────────────────
        .route(
            "/api/v2/finanzas/jurisdicciones",
            get(finanzas::jurisdicciones_listar).post(finanzas::jurisdicciones_crear),
        )
        .route(
            "/api/v2/finanzas/regimenes",
            get(finanzas::regimenes_listar).post(finanzas::regimenes_crear),
        )
        .route(
            "/api/v2/finanzas/sujetos",
            get(finanzas::sujetos_listar).post(finanzas::sujetos_crear),
        )
        .route(
            "/api/v2/finanzas/sujetos/{id}/baja",
            post(finanzas::sujetos_baja),
        )
        .route(
            "/api/v2/finanzas/declaraciones",
            get(finanzas::declaraciones_listar),
        )
        .route(
            "/api/v2/finanzas/declaraciones/generar",
            post(finanzas::declaraciones_generar),
        )
        .route(
            "/api/v2/finanzas/declaraciones/{id}/presentar",
            post(finanzas::declaracion_presentar),
        )
        .route(
            "/api/v2/finanzas/declaraciones/{id}/pagar",
            post(finanzas::declaracion_pagar),
        )
        // ── finanzas: facturación ───────────────────────────────────────────
        .route(
            "/api/v2/finanzas/comprobantes",
            get(finanzas::comprobantes_listar).post(finanzas::comprobantes_emitir),
        )
        .route(
            "/api/v2/finanzas/comprobantes/series",
            get(finanzas::comprobantes_series),
        )
        .route(
            "/api/v2/finanzas/comprobantes/{id}/anular",
            post(finanzas::comprobante_anular),
        )
        // ── finanzas: modelo ────────────────────────────────────────────────
        .route(
            "/api/v2/finanzas/proyecciones",
            get(finanzas::proyecciones_listar).post(finanzas::proyecciones_crear),
        )
        .route(
            "/api/v2/finanzas/proyecciones/sensibilidad",
            get(finanzas::proyecciones_sensibilidad),
        )
        .route(
            "/api/v2/finanzas/proyecciones/plan-bienal",
            get(finanzas::proyecciones_plan_bienal),
        )
        .route(
            "/api/v2/finanzas/proyecciones/{id}",
            get(finanzas::proyeccion_detalle),
        )
        .route(
            "/api/v2/finanzas/punto-equilibrio",
            get(finanzas::punto_equilibrio),
        )
        .route("/api/v2/finanzas/kpis", get(finanzas::kpis))
        .route("/api/v2/finanzas/tablero", get(finanzas::tablero))
        .route(
            "/api/v2/vendedores/me/fiscal",
            get(finanzas::vendedor_fiscal),
        )
        // ── interno ─────────────────────────────────────────────────────────
        .route(
            "/internal/finance/sujetos/{usuarioId}",
            get(interno::sujeto),
        )
        .route(
            "/internal/finance/creditos",
            post(interno::registrar_credito),
        )
        .route(
            "/internal/finance/creditos/orden/{orderId}",
            delete(interno::anular_credito),
        )
        .route(
            "/internal/finance/declaraciones",
            get(interno::declaraciones),
        )
}
